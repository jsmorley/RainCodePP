"""Refresh vocabulary from a local Rainmeter 5 checkout and its optional manual."""
import argparse
from collections import Counter
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rainmeter", type=Path)
    parser.add_argument("--manual", type=Path)
    args = parser.parse_args()

    xml = (ROOT / "Config/Languages.xml").read_text(encoding="utf-8")
    words = [set(group.split()) for group in re.findall(r'<Keywords name="\d">(.*?)</Keywords>', xml, re.S)]
    spellings = {}
    documented_options = {}
    documented_values = {}

    def remember(term):
        spellings[term.lower()] = term

    source = args.rainmeter
    names = Counter()
    for folder in ("Library", "Plugins", "Application"):
        for file in (source / folder).rglob("*.cpp"):
            contents = file.read_text(encoding="utf-8-sig", errors="replace")
            names.update(re.findall(r'\bL"([@A-Za-z][\w@:-]{0,70})"', contents, re.ASCII))
            for option in re.findall(r'\bRead\w+<"([@A-Za-z][\w@]{0,70})">', contents, re.ASCII):
                words[0].add(option.lower())
                remember(option)
            tables = {
                name: re.findall(r'\{\s*L"([\w-]+)"\s*,', table)
                for name, table in re.findall(r'EnumOption<[^;\n]+?>\s+(\w+)\[\]\s*=\s*\{(.*?)\};',
                                              contents, re.S)
            }
            for key, table in re.findall(r'ReadEnum<"(\w+)">\s*\([^;]+?,\s*(\w+)\s*\)', contents):
                for value in tables.get(table, []):
                    words[2].add(key.lower())
                    words[3].add(key.lower() + "=" + value.lower())
                    remember(key)
                    spellings.setdefault(value.lower(), value)

    if args.manual:
        for file in sorted(args.manual.rglob("*.html")):
            contents = file.read_text(encoding="utf-8-sig", errors="replace")
            for key, value in re.findall(r'<code>([@A-Za-z][\w@]*)\s*=\s*([\w-]+)</code>', contents):
                pair = key.lower() + "=" + value.lower()
                if pair in words[3] or pair in words[7]:
                    documented_values.setdefault(pair, value)
            for key, body in re.findall(r'<dt\b[^>]*>\s*<code>([@A-Za-z][\w@]*)</code>(.*?)(?=<dt\b|</dl>)',
                                        contents, re.S):
                documented_options.setdefault(key.lower(), key)
                for value in re.findall(r'<code>([\w-]+)</code>', body):
                    pair = key.lower() + "=" + value.lower()
                    if pair in words[3] or pair in words[7]:
                        documented_values.setdefault(pair, value)
            for term in re.findall(r'<code>([!#$@A-Za-z][\w@:-]*)</code>', contents, re.ASCII):
                spellings.setdefault(term.lstrip("!#$").lower(), term.lstrip("!#$"))

    for term, _ in names.most_common():
        if term != term.lower():
            spellings.setdefault(term.lower(), term)

    bangs = (source / "Library/CommandHandler.cpp").read_text(encoding="utf-8-sig")
    # The registered table supplies both canonical case and newly added commands.
    for name in re.findall(r'\{\s*Bang::\w+,\s*L"([\w:]+)"', bangs):
        if name.lower() not in words[8]:
            words[4].add(name.lower())
        remember(name)

    words[2].add("syntaxversion")
    words[3].update(("syntaxversion=1", "syntaxversion=2"))
    # Put each option in its most specific category where the classification allows it.
    words[0].difference_update(words[1] | words[2] | words[6] | {"shape****"})

    def canonical(term, group):
        if "=" in term:
            option, value = term.split("=", 1)
            return option + "=" + documented_values.get(term, spellings.get(value, value))
        if group == 5:
            return term.upper()
        if ":" in term and term not in spellings:
            return ":".join(spellings.get(part, part[:1].upper() + part[1:]) for part in term.split(":"))
        if group in (0, 1, 2, 6) and term in documented_options:
            return documented_options[term]
        return spellings.get(term, term)

    lines = ["// Generated by Build/UpdateVocabulary.py. See Config/Languages.xml.",
             "constexpr std::string_view Vocabulary[] = {"]
    for index, group in enumerate(words):
        terms = sorted((canonical(term, index) for term in group), key=str.lower)
        lines.append('    R"terms(')
        lines.extend(" ".join(terms[i:i + 8]) for i in range(0, len(terms), 8))
        lines.append(')terms",')
    lines.append("};")
    (ROOT / "RainSyntax/Vocabulary.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

